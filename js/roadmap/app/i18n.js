  const DICTS = { es: ES, en: EN };
  let lang = 'es';

  function detect() {
    let stored = null;
    try {
      stored = localStorage.getItem('jsquest-lang');
    } catch {}
    if (stored === 'es' || stored === 'en') return stored;
    return (navigator.language || 'es').toLowerCase().startsWith('es') ? 'es' : 'en';
  }

  /** t('key') o t('key', ...args) cuando el texto lleva datos. */
  function t(key, ...args) {
    const entry = DICTS[lang][key] ?? ES[key];
    if (entry === undefined) return key;
    return typeof entry === 'function' ? entry(...args) : entry;
  }

  window.I18n = {
    t,
    detect,
    get lang() {
      return lang;
    },
    set(next) {
      lang = DICTS[next] ? next : 'es';
      document.documentElement.lang = lang;
    },
  };
  window.I18n.set(detect());
