/// Escoge el idioma de un texto del contenido: un Map { es, en } o un String tal cual.
String tx(Object? v, String lang) {
  if (v == null) return '';
  if (v is Map) return (v[lang] ?? v['es'] ?? '').toString();
  return v.toString();
}

